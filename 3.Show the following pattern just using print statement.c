/* Show the following pattern just using print statement.
   
   Right half pyramid 
    *
    * *
    * * *
    * * * *
    * * * * *     

   Reverse Right half pyramid
    * * * * * 
    * * * * 
    * * * 
    * * 
    * 
    
   Left half pyramid
            * 
          * * 
        * * * 
      * * * * 
    * * * * *  */
    
    

#include<stdio.h>

int main(){
    
    // Right half pyramid
    printf("*        \n* *      \n* * *    \n* * * *  \n* * * * *\n");
    
    //Reverse Right half pyramid
    printf("\n* * * * *\n* * * *  \n* * *    \n* *      \n*        \n");
    
    //Left half pyramid
    printf("\n        *\n      * *\n    * * *\n  * * * *\n* * * * *\n");
    return 0;
}



















